import type { Alert } from "../api/types";
import { useI18n } from "../i18n";
import { Badge, EmptyState } from "./ui";

const sev = { info: "info", warning: "warn", critical: "danger" } as const;

export function AlertList({ alerts, onAcknowledge, showPatient, busyId }: { alerts: Alert[]; onAcknowledge?: (a: Alert) => void; showPatient?: boolean; busyId?: number | null }) {
  const { t, fmt } = useI18n();
  if (!alerts.length) return <EmptyState>{t("alert.none")}</EmptyState>;
  return (
    <ul className="timeline">
      {alerts.map((a) => (
        <li key={a.id}>
          <div className="stack-sm">
            <div className="row">
              <Badge variant={sev[a.severity]}>{t(`alert.severity.${a.severity}`)}</Badge>
              <Badge variant={a.status === "open" ? "primary" : ""}>{t(`alert.state.${a.status}`)}</Badge>
              {showPatient && <span className="mono xs">{a.patient_id}</span>}
            </div>
            <div>{t(a.message_key)}</div>
            <div className="xs muted num">{fmt.dateTime(a.created_at)} · {a.auto_generated ? t("alert.autoGenerated") : ""}</div>
            {a.status === "acknowledged" && <div className="xs muted">{t("alert.acknowledgedBy", { who: a.acknowledged_by ?? "—" })} · <span className="num">{fmt.dateTime(a.acknowledged_at)}</span></div>}
            {a.status === "open" && onAcknowledge && <div><button className="btn sm" disabled={busyId === a.id} onClick={() => onAcknowledge(a)}>{t("alert.acknowledge")}</button></div>}
          </div>
        </li>
      ))}
    </ul>
  );
}
